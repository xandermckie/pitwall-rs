export function genericPath(): TrackPoint[] {
  const pts: TrackPoint[] = [];
  for (let i = 0; i < 20; i += 1) {
    const angle = (i / 20) * Math.PI * 2;
    pts.push({
      x: 0.5 + (0.34 + 0.05 * Math.sin(angle * 3)) * Math.cos(angle),
      y: 0.5 + (0.29 + 0.04 * Math.cos(angle * 2)) * Math.sin(angle),
    });
  }
  pts.push(pts[0]);
  return pts;
}

export function pathForCircuit(name: string): TrackPoint[] {
  return TRACK_PATHS[name] ?? genericPath();
}
